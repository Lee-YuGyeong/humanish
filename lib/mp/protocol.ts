/**
 * 멀티플레이 프로토콜 — 클라이언트와 워커가 공유하는 **유일한 계약**.
 * 소유: A. app/world/net/* 와 worker/src/* 가 이 파일 하나만 본다.
 *
 * 규칙 네 가지 (worker/README.md에도 같은 내용이 있다):
 *  1. 양쪽 핸들러(RoomDO.webSocketMessage · RoomConnection.onmessage)를 **같은 커밋에서** 고친다.
 *  2. 양쪽 switch의 default는 **무시**한다. 필드·타입 추가는 non-breaking이다.
 *     ★ 단 **union 멤버를 늘리는 건 non-breaking이 아니다** — 구 클라가 새 값을 조용히
 *       default로 흘려서 화면이 멈춘 채 아무 에러도 안 난다. 그래서 RoundWinner 처럼
 *       "언젠가 늘어날 게 뻔한" 값은 **지금 미리 넣어 둔다** (아래 RoundWinner 참고).
 *  3. PROTOCOL_VERSION은 **의미가 바뀔 때만** 올리고, 올렸으면 워커를 먼저 배포한다.
 *  4. 위조되면 곤란한 값은 애초에 C2S에 넣지 않는다. 닉네임·좌석·시각은 전부 서버가 정한다.
 *
 * ┌─ ★ I1 — 이 계약의 급소 ───────────────────────────────────────────────────┐
 * │ 이 파일의 어떤 타입에도 `is_bot`에 해당하는 필드를 만들지 않는다.            │
 * │ 봇 아바타는 사람과 **똑같은 PlayerSnapshot**으로 내려가고, 똑같은            │
 * │ player_moved 스트림을 탄다.                                                │
 * │                                                                            │
 * │ **유일한 예외는 `t:'reveal'` 하나뿐이다.** 그 메시지가 나가는 시점은 판정이  │
 * │ 이미 끝난 뒤이고, 정체 공개가 곧 게임의 결말이다 (SPEC §18.4). 그 전에는     │
 * │ 어떤 필드로도 — 값·개수·순서·길이·도착 시각 어느 것으로도 — 봇이 새면 안 된다.│
 * │                                                                            │
 * │ 새 필드를 더할 때 물어야 할 것은 "이 값이 봇인가?"가 아니라                  │
 * │ **"이걸 몇 판 모으면 봇을 골라낼 수 있나?"** 다. 예: 좌석별 투표 완료 표시는  │
 * │ 값 자체엔 정체가 없지만 조기 종료와 겹치면 "안 낸 자리 = 봇"이 확정된다.      │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * ┌─ ★ v3 — 명부의 뜻이 바뀌었다 (welcome · player_joined · player_left) ──────┐
 * │ v2 까지 명부는 "지금 **소켓이 붙어 있는** 사람 + 봇 전부"였다. 그게 이 계약   │
 * │ 에서 제일 크게 샌 자리다:                                                   │
 * │   · 방에 제일 먼저 들어가면 사람 쪽이 통째로 비어서 **players[] 가 곧 봇      │
 * │     명단**이었다. 좌석순 정렬은 아무 방어도 되지 않았다 — 개수가 답이었다.    │
 * │   · player_joined / player_left 는 **사람에게만** 났다. 4분짜리 판에서 거기   │
 * │     한 번이라도 등장한 id 는 사람 확정이고, 새로고침 한 번이면 아웃이었다.    │
 * │                                                                            │
 * │ 그래서 명부를 **좌석 명단**으로 바꿨다. 접속 여부는 명부에 나타나지 않는다:   │
 * │   · welcome 은 meta.seats **전부**를 담는다 (미접속 사람 포함).              │
 * │   · player_joined / player_left 는 **좌석이 생기거나 없어질 때만** 난다.      │
 * │     사람·봇을 가리지 않는다 — 게임이 시작돼 봇 좌석이 생기는 순간도 여기다.   │
 * │   · 소켓이 끊겨도 아무 이벤트도 안 난다. 그 아바타는 마지막 자세로 남는다.    │
 * │     "가만히 서 있는 사람"과 구분되지 않아야 하기 때문이다.                    │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * ★ v2 — 라운드테이블이 **순차 발언(turn)에서 다같이 말하기(speak)로** 바뀌었다.
 *   `RoundPhase`의 멤버가 갈렸고(`turn`/`revote` 제거, `speak`/`verdict`/`reveal`/
 *   `ended` 추가) `t:'round'`의 필드 의미도 바뀌었다(turnIndex/turnTotal →
 *   round/totalRounds/nomineeId). **기존 값의 의미가 바뀌었으므로** 규칙 3에 따라
 *   PROTOCOL_VERSION을 2로 올린다 (lib/mp/constants.ts).
 *   순차 발언을 버린 이유는 두 가지다 — 판 길이가 인원수에 비례해 늘어나고,
 *   "그 25초를 어떻게 채우는지"가 곧 봇 표식이었다 (I1, docs/GAMEFLOW-V2.md §4).
 */

/**
 * 아바타 애니메이션 상태. 서버가 화이트리스트로 검증한다.
 *
 * ★ 여기에 'jump'를 넣지 않는다. 이 목록은 **서버가 거르는 화이트리스트**라,
 *   값을 늘리면 구 워커가 새 클라의 move를 통째로 버린다 — 뛰는 동안 그 사람이
 *   남의 화면에서 얼어붙는다. 공중인지는 `y > 0`으로 받는 쪽이 판단한다.
 */
export type AnimState = 'idle' | 'walk' | 'run' | 'sit';

export const ANIM_STATES: readonly AnimState[] = ['idle', 'walk', 'run', 'sit'];

/**
 * 방에 있는 한 사람(또는 봇)의 현재 모습.
 *
 * ★ 필드를 더할 때마다 "이걸로 봇을 골라낼 수 있나"를 먼저 묻는다 (SPEC §7.2와 같은 규칙).
 *   예: `joinedAt`을 넣으면 봇은 방 생성 시각에 뭉쳐 있어서 전부 특정된다.
 */
export interface PlayerSnapshot {
  /** players.id (uuid). 방 안에서만 유효하다. */
  id: string;
  /** 1 ~ room.capacity. 표시 순서·색을 여기서 뽑는다. */
  seat: number;
  /** '익명1' 형태. 클라이언트가 보낸 값을 절대 쓰지 않는다 — 티켓에 서명된 값이다. */
  nickname: string;
  /** 아바타 외형 키. `mask-01` 형태. */
  maskId: string;
  x: number;
  z: number;
  /**
   * 발 높이. 0이 바닥이고 점프·가구 위에서만 >0이다.
   * 나중에 붙은 필드라 **구 클라이언트는 보내지 않는다** — 없으면 0으로 읽는다.
   */
  y: number;
  /** y축 회전(rad). 아바타가 보는 방향. */
  heading: number;
  anim: AnimState;
}

/** 클라이언트 → 서버 */
export type C2SMessage =
  | { t: 'move'; x: number; z: number; y: number; heading: number; anim: AnimState }
  | { t: 'chat'; text: string }
  /**
   * 인트로 영상이 끝났다 — 라운드테이블 판을 시작해도 된다는 신호.
   * 여러 사람이 제각기 보내지만 **첫 신호에만** 판이 열리고 나머지는 무시된다
   * (서버 maybeStartRound 가 이미 열린 판이면 그냥 돌아간다). 위조돼도 그 방의
   * 3D 연출이 조금 일찍 시작될 뿐이라 값 검증은 없다.
   */
  | { t: 'intro_done' }
  /**
   * 지목 투표. **vote 페이즈에서만 유효**하고 그 밖에서는 서버가 버린다.
   *
   * · 좌석당 1표. 마감까지 **몇 번이든 다시 보낼 수 있고 마지막 것이 유효하다**
   *   (사람이 마음을 바꾸는 건 자연스럽다 — 못 바꾸게 하면 오히려 봇처럼 군다).
   * · **자기 자신은 못 찍는다.** 서버가 하드 거부한다 (SPEC §18.3 — 연기자 자폭 지목 차단).
   *   이건 봇에게도 똑같이 걸린다: reveal 의 votes[] 에 자기 자신 투표가 한 건이라도
   *   보이면 그 자리가 봇으로 확정된다 (I1).
   * · voter 는 **소켓에서** 되찾는다. 규칙 4대로 "내가 누구인지"는 C2S에 넣지 않는다.
   */
  | { t: 'vote'; targetId: string }
  /**
   * 생사 재투표(찬=처형 / 반=생존). **verdict 페이즈에서만 유효**하다.
   * 지목된 본인의 표는 서버가 무시한다(기권).
   */
  | { t: 'verdict'; guilty: boolean }
  /**
   * 한 판 더 — **끝난 판(done)에서만** 유효하고 그 밖에서는 서버가 버린다.
   * intro_done 과 같은 "첫 신호만" 규칙이다: 첫 rematch 가 판을 비우고 새로 열면
   * 나머지는 이미 열린 판이라 그냥 무시된다. 위조돼도 끝난 판이 다시 도는 것뿐이다.
   */
  | { t: 'rematch' };

/**
 * 라운드테이블 진행 단계.
 *
 * ┌─ v2에서 뒤집힌 것 (읽고 되돌리지 말 것) ──────────────────────────────────┐
 * │ v1의 이 주석은 "워커는 게임 규칙을 모른다 — 집계와 정체 판정은 Supabase가   │
 * │ 소유한다"였다 (MULTIPLAYER §8). **3D 월드 한정으로 그 결정을 뒤집었다.**    │
 * │ 월드 워커가 표를 모으고, 지목을 확정하고, 정체를 판정해서 reveal 까지 낸다. │
 * │                                                                            │
 * │ 그래서 I1이 지켜지는 근거가 **바뀌었다.** 전에는 "워커가 정체를 몰라서"     │
 * │ 구조적으로 안 샜다. 이제는 **"알지만 reveal 말고는 안 내보내서"** 안 샌다 — │
 * │ 즉 규율로만 지켜진다. 정체가 실리는 S2C는 t:'reveal' **하나뿐이어야 하고**, │
 * │ 그걸 만드는 코드도 워커 안 한 군데로 좁혀 둔다.                             │
 * │                                                                            │
 * │ 2D 게임(Supabase 페이즈 상태머신)은 여전히 자기 집계를 한다. 두 무대는       │
 * │ 별개다 — 이 enum을 lib/game/types.ts 의 Phase 와 맞추려 들지 말 것.        │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 단계 자체로는 봇이 새지 않는다 (I1):
 *   · speak 은 **전원이 동시에** 말한다. 누구 차례라는 게 없으니 "그 차례를 어떻게
 *     채우는가"라는 관찰 창 자체가 사라진다 (turn 을 버린 이유).
 *   · 조명(spotlightId)이 켜지는 단계는 **defense 하나뿐**이고, 그건 이미 공개된
 *     지목 대상이다. 그 밖의 단계에서 조명이 켜지면 그 자체가 신호다.
 *   · 모든 단계 길이는 대상의 정체와 무관하게 고정이다 (§5.3 대칭). defense 는
 *     지목된 자리가 사람이든 봇이든 시간을 꽉 채운다 — 조기 종료가 없다.
 *
 * ★ 단계마다 **누가 움직이고 누가 말할 수 있는지**는 여기 적지 않는다.
 *   lib/mp/constants.ts 의 MOVEMENT_LOCKED_PHASES · CHAT_LOCKED_PHASES · mayChat
 *   하나뿐이고, **워커와 클라이언트가 그걸 같이 읽는다.** 목록을 어느 한쪽에
 *   복붙하면 그 순간 갈리고, 갈린 단계는 통째로 정체 관찰 창이 된다 (I1).
 */
export type RoundPhase =
  | 'idle' // 진행 전 (intro_done 대기)
  | 'topic' // 주제 제시 (중앙 스크린). 조명 없음
  | 'speak' // **다같이 말하기** — 전원이 동시에 주제에 답한다. 조명 없음
  | 'freechat' // 자유 대화 — 추궁·반박
  | 'vote' // 지목 투표 (자기 자신 금지)
  | 'defense' // 최후변론 — 지목된 한 명에게만 조명
  | 'verdict' // 생사 재투표 (찬=처형 / 반=생존). 지목된 본인은 기권
  | 'reveal' // 결과 · 정체 공개
  | 'ended'; // 판 종료. **다시 시작하지 않는다**

/**
 * 이긴 진영.
 *
 * ★ `'actor'`(연기자 승, SPEC §18.4)는 **월드 무대에서 아직 나오지 않는다** —
 *   워커는 `is_bot` 만 알고 역할(citizen/actor)은 모른다 (worker/src/room-meta.ts 의
 *   SeatRow 에 역할 필드가 없다). 그래도 지금 넣어 두는 이유는 규칙 2의 단서 때문이다:
 *   나중에 union 멤버를 늘리면 구 클라가 조용히 default 로 흘려 결과 화면이 빈다.
 *   지금 넣는 건 공짜고, 나중에 넣는 건 버전 올림이다.
 */
export type RoundWinner = 'citizen' | 'ai' | 'actor';

/**
 * 한 좌석의 진영 (SPEC §18.2 — 예전 이름 '스파이'는 쓰지 않는다).
 * 연기자('actor')는 AI 인 척하는 **사람**이다. 수는 0~상한 균등 랜덤이고 비공개 —
 * 밖으로 나가는 자리는 각자에게 가는 `t:'role'` 과 reveal 의 identities 둘뿐이다.
 */
export type RoundRole = 'citizen' | 'actor' | 'ai';

/** reveal 에서 공개하는 한 표. 누가 누구를 찍었나 (사람·봇 전부). */
export interface RevealVote {
  voterId: string;
  targetId: string;
}

/**
 * ★ I1의 **유일한 예외.** 이 타입을 다른 메시지에 재사용하지 마라 —
 *   재사용하는 순간 정체가 reveal 밖으로 나갈 통로가 생긴다.
 */
export interface RevealIdentity {
  id: string;
  isBot: boolean;
  /**
   * 진영. `isBot` 과 겹치지만(role==='ai' ⇔ isBot) 지우지 않는다 — 구 워커가
   * 이 필드 없이 보낼 수 있어서, 클라이언트는 없으면 isBot 으로 접는다.
   */
  role?: RoundRole;
}

/** 접속이 거절되는 이유. 클라이언트가 이걸 보고 재시도할지 정한다. */
export type ErrorCode =
  | 'version_mismatch'
  | 'unauthorized'
  | 'room_full'
  | 'room_unavailable'
  | 'bad_request';

/** 서버 → 클라이언트 */
export type S2CMessage =
  /**
   * 방의 **명부 전부** — 좌석 명단이다 (v3 상자). 접속 중인 사람만 담지 않는다.
   * 미접속 사람도 마지막 자세(없으면 스폰 자리)로 들어 있고, 봇과 **같은 모양**이다.
   * 좌석 오름차순 — 사람 먼저·봇 먼저로 모으면 배열 순서가 곧 답이 된다 (I1).
   */
  | { t: 'welcome'; selfId: string; players: PlayerSnapshot[] }
  /**
   * 명부에 **좌석이 생겼다.** 접속이 아니다 — 사람이 접속하거나 새로고침해도 안 난다.
   * 사람 좌석·봇 좌석을 가리지 않는다(게임이 시작돼 봇이 생기는 순간이 대표적이다).
   * ★ 여기서 사람만 걸러 내보내는 순간 이 메시지가 곧 사람 명단이 된다 (I1).
   */
  | { t: 'player_joined'; player: PlayerSnapshot }
  /**
   * 명부에서 **좌석이 없어졌다.** 소켓 종료가 아니다 — 끊긴 사람의 아바타는 남는다.
   * (남겨야 "나간 자리 = 사람"이 안 된다. 가만히 서 있는 것과 구분되지 않는다.)
   */
  | { t: 'player_left'; id: string }
  | {
      t: 'player_moved';
      id: string;
      x: number;
      z: number;
      /** 발 높이. 0이 바닥이다 (PlayerSnapshot.y와 같은 값) */
      y: number;
      heading: number;
      anim: AnimState;
    }
  | { t: 'chat'; id: string; nickname: string; text: string; ts: number }
  | {
      /**
       * 라운드테이블 진행 상태. 단계가 바뀔 때마다, 그리고 **새로 들어온 사람에게 한 번**
       * 보낸다 (안 보내면 판 중간 입장자의 화면이 idle 로 멈춘다).
       * ★ endsAt 은 **서버 now() 기준**이다. 클라이언트 카운트다운은 표시용이다 (I2) —
       *   단계 전환 판정은 오직 서버가 한다.
       */
      t: 'round';
      phase: RoundPhase;
      /** 중앙 스크린 주제. 없으면 null */
      topic: string | null;
      /** 이 단계가 끝나는 서버 시각(epoch ms) */
      endsAt: number;
      /** 지금 몇 번째 주제 라운드인가 (1-based). 주제 라운드가 아닌 단계에선 0 */
      round: number;
      /** 주제 라운드 총 수 (ROUND_TOPIC_ROUNDS). 진행 표시(①/②)용 */
      totalRounds: number;
      /**
       * 조명받는 players.id. **defense 단계에서만 채워지고 그 밖엔 반드시 null**이다.
       * **봇 여부 아님** (I1) — 이미 공개된 지목 대상일 뿐이다.
       * ★ 조명의 소스는 언제나 이 필드 **하나**다. nomineeId 로 조명을 켜지 말 것 —
       *   두 값이 갈리면 "어느 게 조명인가"가 모호해지고 그 틈이 곧 누출 통로가 된다.
       */
      spotlightId: string | null;
      /**
       * vote 집계 뒤 확정된 지목 대상. **defense 부터** 채워진다. 그 전에는 null이고,
       * 지목이 없으면(사람 표 0장) 끝까지 null이다.
       * ★ 이 값은 defense 진입 **전에는 절대 나가면 안 된다** — 나가면 vote 마감 전에
       *   결과가 새고, 판 중간 입장자에게 미리 흘리는 경로도 여기서 생긴다.
       */
      nomineeId: string | null;
    }
  /**
   * 투표 진행 현황. **숫자 둘뿐이다.**
   *
   * ┌─ 왜 좌석을 싣지 않는가 (I1 + 게임성) ─────────────────────────────────────┐
   * │ 누가 누구를 찍었는지는 게임성 때문에 감춘다 — 마감 전에 보이면 눈치싸움이   │
   * │ 아니라 줄서기가 된다.                                                      │
   * │                                                                            │
   * │ **누가 냈는지(voterId)도 싣지 않는다.** 이쪽이 I1이다. vote 에는 "사람 전원 │
   * │ 제출" 조기 종료가 있는데(SPEC §5.1), 좌석별 완료 표시가 같이 있으면          │
   * │ **"조기 종료가 걸렸는데 아직 안 낸 자리 = 봇 확정"** 이 된다. 한 판에 전     │
   * │ 좌석이 갈린다. 익명 카운트라서 안전한 것이지 "표가 안 보여서" 안전한 게 아니다.│
   * │                                                                            │
   * │ ★ voted 는 **표를 낸 고유 좌석 수**다. 수신한 vote 메시지 수가 아니다 —     │
   * │   그렇게 세면 표를 바꾼 사람이 카운트를 두 번 올려 변경 행위가 관측된다.     │
   * │ ★ total 은 **전 좌석 수**다. 사람 좌석 수로 두지 않는다.                    │
   * │ ★ 이 메시지는 표마다 즉시 쏘지 않고 **고정 간격으로 묶어** 보낸다            │
   * │   (VOTE_PROGRESS_INTERVAL_MS). 즉시 쏘면 봇 표는 100ms 틱 위에, 사람 표는   │
   * │   수신 즉시 나가서 **도착 시각의 상관으로 봇 표가 갈린다** — SPEC §6.1이     │
   * │   Broadcast 를 버리고 폴링을 택한 것과 같은 이유다.                         │
   * └──────────────────────────────────────────────────────────────────────────┘
   */
  | { t: 'vote_progress'; voted: number; total: number }
  /**
   * 처형이 확정된 순간. reveal 직전에 **딱 한 번** 보낸다 (아바타가 쓰러지는 연출용).
   * 처형이 없으면 아예 안 나간다.
   * ★ 정체는 여기 실리지 않는다 — 쓰러지는 것과 그가 봇이었는지는 별개다.
   */
  | { t: 'eliminated'; id: string }
  /**
   * ┌─ ★★ I1의 **유일한 예외** ────────────────────────────────────────────────┐
   * │ 이 메시지에만 정체(identities)가 실린다. 판정이 끝난 뒤에 나가고, 정체      │
   * │ 공개가 곧 게임의 결말이기 때문이다 (SPEC §18.4).                           │
   * │                                                                            │
   * │ 지켜야 할 것 셋:                                                           │
   * │  · **phase 가 reveal 에 도달하기 전에는 절대 보내지 않는다.** 판 중간       │
   * │    입장자·재접속자에게 스냅샷으로 흘리는 경로가 생기기 쉽다 (규칙 4의 결).   │
   * │  · 이 메시지를 만드는 코드는 **워커 안 한 함수**로 좁힌다. is_bot 을 읽는   │
   * │    자리가 늘어나는 만큼 새어 나갈 확률이 곱으로 는다.                       │
   * │  · identities 는 **전 좌석**을 담고 **좌석 순서**로 낸다. 봇만 담거나 봇을   │
   * │    앞/뒤에 몰아 담으면 배열 순서 자체가 답이 된다.                          │
   * └──────────────────────────────────────────────────────────────────────────┘
   */
  | {
      t: 'reveal';
      /** 확정된 지목 대상. 사람 표가 한 장도 없었으면 null (지목 없음 → 처형 없음) */
      nomineeId: string | null;
      /** 처형됐는가. verdict 에서 찬이 과반일 때만 true — 동수는 생존이다 */
      executed: boolean;
      winner: RoundWinner;
      /** 생사 재투표 집계. 지목된 본인의 표는 빠져 있다 */
      verdict: { guilty: number; innocent: number };
      /** 누가 누구를 찍었나. 사람·봇 전부 */
      votes: RevealVote[];
      /** ★ 정체. 전 좌석, 좌석 순서 */
      identities: RevealIdentity[];
    }
  /**
   * 내 역할 — **이 소켓 하나에만** 간다 (§18.2 — 자기 역할만 안다, 연기자끼리도
   * 서로 모른다). 판이 열릴 때, 그리고 판 도중 재접속할 때 한 번. 봇 좌석에는
   * 소켓이 없으니 애초에 갈 곳이 없다.
   * ★ 브로드캐스트에 실으면 그 순간 연기자 명단이 방 전체에 새는 것이다 —
   *   이 메시지는 반드시 소켓 단위 send 로만 보낸다.
   */
  | { t: 'role'; role: 'citizen' | 'actor' }
  | { t: 'error'; code: ErrorCode };

