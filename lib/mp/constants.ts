/**
 * 이 단계에서는 **아무도 움직이지 않는다.** 사람은 UI 를 만져야 해서 포인터락이
 * 풀리고(그래서 걸을 수 없고), 봇은 haltBot 으로 선다.
 *
 * ★ defense 는 여기 **없다.** 한동안 넣어 뒀는데(사람만 움직이면 그 20초가 통째로
 *   관찰 창이 되니까), 그러면 변론을 듣는 20초 동안 방 전체가 정지 화면이 된다.
 *   답은 "아무도 안 움직인다"가 아니라 **"변론하는 사람만 선다"** 였다 — 아래 mayMove.
 *   지목된 자리는 이미 조명으로 공개돼 있으므로 그 한 자리가 서 있는 건 아무것도
 *   흘리지 않는다. 나머지는 사람도 봇도 평소대로 걷는다(대칭).
 */
export const MOVEMENT_LOCKED_PHASES: readonly RoundPhase[] = ['vote', 'verdict', 'reveal'];

/**
 * 이 단계에서는 **아무도 말하지 않는다.** 봇은 발화 예약이 끊기고(hushBots),
 * 사람은 **서버가 채팅을 거절한다.**
 *
 * ★ 클라 UI 만 막으면 안 된다. 소켓으로 그냥 보내면 그대로 방에 뿌려지고,
 *   봇의 발화 확률이 이 구간에서 **정확히 0** 이라 한 줄이면 그 자리가 사람 확정이다.
 *
 * ★ defense 는 여기 **없다** (2026-08-06 결정 — CEO 지시). 최후변론 20초 동안
 *   지목된 한 명만 말하게 했더니 "나머지는 왜 못 말하냐"가 문제였다. 그래서 전원에게
 *   열었다 — 사람도 봇도 평소(freechat)처럼 말한다. **여는 방식이 핵심이다:**
 *   defense 를 이 목록에서 빼면 hushBots 가 안 돌고 botsMayChat(= mayChat(phase,false))도
 *   열려서 봇이 **같이** 말한다(대칭). 그러면 "봇 확률 정확히 0" 조건이 사라져 한 줄 친
 *   자리가 사람 확정이 되지 않는다 — 사람만 열었다면 그게 그대로 I1 누출이다.
 *   지목된 자리는 여전히 조명(spotlightId)과 정지(mayMove)로 도드라진다.
 *
 * ┌─ ★★ vote · verdict 도 뺐다 (2026-08-07, 사용자 지시) ────────────────────────┐
 * │ "처형 투표할 때 얘기를 못 하니 좀 그렇다." 지목 30초 + 판결 20초, 판에서 제일 │
 * │ 말이 하고 싶은 50초가 통째로 침묵이었다. 그래서 defense 때와 **똑같은 방식**  │
 * │ 으로 연다 — 목록에서 빼면 hushBots 가 안 돌고 botsMayChat 도 같이 열려서      │
 * │ 봇이 사람과 함께 말한다. 한쪽만 여는 순간 I1 누출이라는 게 이 목록의 요점이고, │
 * │ 목록에서 빼는 것이 **양쪽을 동시에** 여는 유일한 방법이다.                    │
 * │                                                                            │
 * │ ★ 그래서 이 목록은 이제 MOVEMENT_LOCKED_PHASES 와 **다르다.** vote·verdict 는 │
 * │   "못 움직이지만 말은 되는" 구간이다 — 패널을 만져야 해서 포인터락이 풀리고    │
 * │   (그래서 다리는 묶이고), 키보드는 잠금과 무관하므로 입력줄은 열린다.          │
 * │   봇도 정확히 같다: haltBot 으로 서 있고, takeSpeech 는 그대로 돈다. 두 축이   │
 * │   갈린 것이지 대칭이 깨진 게 아니다 — 대칭은 **축마다** 지키면 된다.          │
 * │                                                                            │
 * │ ★ reveal 만 남는다. 거긴 이미 전 좌석의 정체가 공개된 뒤라 I1 이 걸리지 않지만, │
 * │   판이 끝나는 경계에서 **넘어온 발화를 끊어 주는 자리**가 하나는 있어야 한다   │
 * │   (verdict 에 예약된 말이 결과 화면 위에서 터지는 것). 그 역할이 여기다.       │
 * └──────────────────────────────────────────────────────────────────────────┘
 */
export const CHAT_LOCKED_PHASES: readonly RoundPhase[] = ['reveal'];

/**
 * 이 단계에 **UI 가 떠서 포인터락을 풀어야 하는가.**
 *
 * ★ "움직일 수 있는가"를 이걸로 묻지 마라 — 그건 mayMove 다. defense 는 여기 없지만
 *   지목된 한 자리는 못 움직인다. 둘이 갈라진 게 이 단계의 요점이다.
 */
export function isMovementLocked(phase: RoundPhase): boolean {
  return MOVEMENT_LOCKED_PHASES.includes(phase);
}

/** 이 단계에 예약된 발화를 끊어야 하는가 (봇의 hushBots · 클라의 입력창 닫기). */
export function isChatLocked(phase: RoundPhase): boolean {
  return CHAT_LOCKED_PHASES.includes(phase);
}

/**
 * 이 좌석이 지금 말할 수 있는가. **워커와 클라이언트가 같이 읽는 유일한 판정이다.**
 *
 * ★ 이제 reveal 을 뺀 모든 단계가 열려 있다 (CHAT_LOCKED_PHASES 의 두 번째 상자).
 *   "못 움직이는데 말은 되는" 구간(vote·verdict)이 정상이다 — 발화와 이동은 축이
 *   다르고, 대칭은 축마다 따로 지킨다.
 *
 * ┌─ ★ defense 는 이제 전원이 말한다 (2026-08-06, CEO 지시) ─────────────────────┐
 * │ 예전엔 최후변론에서 **지목된 한 명만** 말했다(나머지는 채팅이 막혔다). 그런데 │
 * │ "변론 20초 동안 나머지가 아무 말도 못 한다"가 문제라 전원에게 열었다.        │
 * │                                                                            │
 * │ ★ 사람만 열면 I1 이 샌다 — 봇이 그 구간에 침묵하면(발화 확률 0) 한 줄 친 자리가│
 * │   사람 확정이 되기 때문이다. 그래서 defense 를 CHAT_LOCKED_PHASES 에서 아예   │
 * │   뺐다. 그러면 hushBots 가 안 돌고 botsMayChat(= mayChat(phase,false))도 열려 │
 * │   **봇도 사람과 똑같이** 말한다. 대칭이라 발화 자체는 아무 자리도 특정 못 한다.│
 * │                                                                            │
 * │ ★ 그래서 발화는 더 이상 지목 여부(isNominee)로 갈리지 않는다. 파라미터는 거울상│
 * │   함수 mayMove 와 시그니처를 맞추고 호출부(room-do)를 안 고치려 남긴다 —      │
 * │   조명·정지는 여전히 지목된 한 명만이다 (mayMove).                           │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * @param isNominee 지목 좌석인가. **발화 판정에는 더 이상 쓰지 않는다** (위 상자).
 */
export function mayChat(phase: RoundPhase, isNominee: boolean): boolean {
  void isNominee; // 발화는 단계 잠금만 본다. 지목 여부는 mayMove(조명·정지)만 가른다.
  return !isChatLocked(phase);
}

/**
 * 이 좌석이 지금 **움직일 수 있는가**. mayChat 의 거울상이고, 역시 워커와 클라가
 * 같이 읽는 유일한 판정이다.
 *
 * ┌─ ★ defense 의 이동 규칙 (I1) ─────────────────────────────────────────────┐
 * │ 말하기: 이제 **전원**이 말한다 (mayChat 상자 — 사람·봇 대칭으로 열었다).   │
 * │ 움직이기: 지목된 한 명**만** 선다. 나머지는 사람도 봇도 평소대로 걷는다.   │
 * │                                                                          │
 * │ 왜 나머지를 풀어도 되는가 — 사람과 봇이 **같이** 걷기 때문이다. 예전에      │
 * │ 이 단계를 통째로 잠갔던 건 "봇만 얼어붙고 사람만 걷는" 비대칭 때문이었지,   │
 * │ 정지 자체가 목적이 아니었다. 양쪽 다 걸으면 관찰 창이 생기지 않는다.       │
 * │                                                                          │
 * │ 왜 지목된 자리는 세워도 되는가 — 그 자리는 이미 조명(spotlightId)으로       │
 * │ 방 전체에 공개돼 있다. 이미 아는 자리가 서 있는 건 새 정보가 아니다.        │
 * │ 오히려 변론하는 사람이 돌아다니면 조명이 따라다녀 화면이 산만해진다.        │
 * │                                                                          │
 * │ ★ 지목된 자리가 사람이든 봇이든 **똑같이** 선다. 봇만 세우면(혹은 사람만)   │
 * │   그 한 자리의 정체가 그대로 드러난다 — 이 단계에서 제일 위험한 자리다.     │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * @param isNominee 이 좌석이 지목되어 조명을 받는 자리인가 (round.nomineeId 와 같은가)
 */
export function mayMove(phase: RoundPhase, isNominee: boolean): boolean {
  if (phase === 'defense') return !isNominee;
  return !isMovementLocked(phase);
}

