/**
 * 현실 앵커 — 봇에게 **지금 몇 시인지** 알려 준다. 순수 함수만.
 *
 * ┌─ 왜 필요한가 ─────────────────────────────────────────────────────────────┐
 * │ "지금 몇 시야", "오늘 무슨 요일이야"는 심문자 단골이다. 아무것도 안 알려 주면 │
 * │ 봇은 그럴듯한 시각을 **지어낸다** — 그리고 봇마다 따로 지어낸다.             │
 * │                                                                            │
 * │ 그래서 방 안의 두 봇이 "새벽 3시"와 "오후 2시"로 갈리는 순간이 온다. 그러면   │
 * │ 한 명이 아니라 **둘 다** 걸린다. 사람 여럿이 같은 방에 있는데 시간대가 서로   │
 * │ 다를 수는 없기 때문이다 (I1).                                              │
 * │                                                                            │
 * │ 알람("오늘 알람 몇 시에 맞춰놨어?")·식사("점심 뭐 먹었어?") 같은 질문도       │
 * │ 지금이 몇 시인지 알아야 말이 된다. 밤 10시에 "이따 점심 먹을 거야"는 그       │
 * │ 자체로 표식이다.                                                            │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * ★ 여기서 시계를 읽지 않는다 (I3의 정신). `Date.now()`는 부르는 쪽이 읽어서
 *   ISO 문자열로 넘긴다 — 그래야 검사가 시각을 손으로 먹일 수 있다.
 */

/** 이 게임은 한국어 채팅이다. 봇은 전부 한국에 사는 사람을 연기한다. */
const KST_OFFSET_MS = 9 * 60 * 60 * 1000;

/*
 * ★ Intl(timeZone) 대신 오프셋을 손으로 더한다.
 *   한국은 서머타임이 없어 UTC+9 고정이라 계산이 한 줄이고, 무엇보다 런타임의
 *   ICU 데이터에 기대지 않는다 — 이 코드는 Node(로컬)와 workerd(배포) 양쪽에서
 *   돌고, 시간대 데이터가 빠진 빌드에서 조용히 UTC로 떨어지면 봇이 9시간 어긋난
 *   시각을 자신 있게 말한다.
 */
const WEEKDAYS = ['일', '월', '화', '수', '목', '금', '토'] as const;

/**
 * 시간대 이름. 사람은 "14시"라고 하지 않는다 — "오후 2시"라고 한다.
 * 경계는 한국어 감각에 맞춘다 (11~13시가 '낮', 21시부터 '밤').
 */
function periodOf(hour24: number): string {
  if (hour24 < 6) return '새벽';
  if (hour24 < 11) return '아침';
  if (hour24 < 14) return '낮';
  if (hour24 < 18) return '오후';
  if (hour24 < 21) return '저녁';
  return '밤';
}

/**
 * 분을 5분 단위로 **내린다**.
 *
 * 반올림이 아니라 내림인 이유: 반올림은 59분에서 60이 되어 시(時)를 넘겨야 하고,
 * 그 자리에서 날짜·요일까지 넘어갈 수 있다. 내림에는 그 경계가 없다.
 *
 * 5분으로 뭉개는 건 두 가지를 같이 해결한다 —
 *   · 사람은 "9시 53분"이라고 안 한다. "9시 반쯤", "10시 다 돼감"이라고 한다.
 *   · 같은 방의 두 봇이 몇 초 차이로 물어봐도 **같은 값**을 답한다 (머리말).
 */
function floor5(minute: number): number {
  return Math.floor(minute / 5) * 5;
}

/**
 * ISO 시각 → 봇에게 줄 한 줄. 못 읽을 값이면 null (그러면 블록이 안 붙는다).
 *
 * 예: "8월 3일 월요일, 밤 9시 55분쯤"
 */
export function describeNow(iso: string): string | null {
  const ms = Date.parse(iso);
  if (!Number.isFinite(ms)) return null;

  // UTC 기준 게터를 쓰되 시각을 미리 KST만큼 밀어 둔다 — 이러면 실행 환경의
  // 로컬 시간대가 무엇이든 결과가 같다.
  const d = new Date(ms + KST_OFFSET_MS);
  const hour24 = d.getUTCHours();
  const minute = floor5(d.getUTCMinutes());
  const hour12 = hour24 % 12 === 0 ? 12 : hour24 % 12;

  const date = `${d.getUTCMonth() + 1}월 ${d.getUTCDate()}일 ${WEEKDAYS[d.getUTCDay()]}요일`;
  const time = minute === 0 ? `${hour12}시쯤` : `${hour12}시 ${minute}분쯤`;
  return `${date}, ${periodOf(hour24)} ${time}`;
}
