/**
 * 자리마다 다른 인물을 준다. AI가 둘 이상일 때 같은 성격이면 바로 묶인다.
 *
 * ★ 월드 라우트는 이걸 쓰지 않는다 — 방마다 인물이 갈려야 해서 roomId까지 섞은
 *   `worldPersonaFor`(app/api/internal/world-agent/route.ts)를 쓴다. 월드 AI는 늘
 *   비어 있는 첫 자리에 들어가므로, 자리만 보면 어느 방에서도 같은 인물이 나온다.
 *   이 함수는 자리만 아는 호출자를 위해 남겨 둔다.
 */
export function worldPersonaForSeat(seat: number): Persona {
  return WORLD_PERSONAS[Math.abs(seat) % WORLD_PERSONAS.length];
}
