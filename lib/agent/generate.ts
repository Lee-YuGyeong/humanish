/**
 * 이 인물이 쓸 폴백 줄 (persona.fallbacks). 없으면 공용 풀.
 * 공용 풀 세 줄을 모든 인물이 나눠 쓰면 인물이 뭉개진다 (Persona.fallbacks의 상자).
 */
function fallbackPoolFor(persona: Persona | undefined): readonly string[] {
  const own = persona?.fallbacks;
  return own && own.length > 0 ? own : FALLBACK_POOL;
}

function pickFallbackLine(persona?: Persona): string {
  const pool = fallbackPoolFor(persona);
  return pool[Math.floor(Math.random() * pool.length)];
}

/**
 * 이 문구가 폴백인가. 부르는 쪽이 "알맹이 없는 한마디"를 걸러낼 때 쓴다.
 *
 * ★ FALLBACK_POOL만 보면 안 된다 — 인물별 폴백이 생긴 뒤로 그 목록은 전체가
 *   아니다. 인물을 같이 넘기지 않으면 인물 폴백이 그물을 그냥 통과한다.
 */
export function isFallbackLine(text: string, persona?: Persona): boolean {
  return FALLBACK_POOL.includes(text) || fallbackPoolFor(persona).includes(text);
}

/**
 * 실패한 봇의 대체 발화 (§12.3). route의 catch에서도 쓴다.
 * 지연에 지터를 준다 — 실패분이 같은 순간에 우르르 뜨면 그것만으로 봇이 묶인다 (I1).
 */
export function fallbackOutput(
  // persona는 선택이다 — route의 catch처럼 인물을 모르는 자리에서도 부른다.
  ctx: (Pick<AgentContext, 'suspicionOnMe'> & Partial<Pick<AgentContext, 'persona'>>) | undefined,
  reason: string,
): AgentOutput {
  // 인물을 알면 그 인물의 폴백을 쓴다. route의 catch처럼 모르는 자리는 공용 풀.
  const line = pickFallbackLine(ctx?.persona);
  return {
    messages: [line],
    delaysMs: [typingDelayMs(line) + Math.floor(Math.random() * 1_500)],
    reasoning: `fallback: ${reason}`,
    suspicionOnMe: ctx?.suspicionOnMe ?? 0,
    action: 'answer',
    // 폴백은 아무것도 지어내지 않았다. 여기서 사실을 남기면 봇이 "ㅇㅇ"라고만
    // 하고서 무언가를 말했다고 기억한다.
    facts: [],
  };
}

