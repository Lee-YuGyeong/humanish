export interface AgentOutput {
  messages: string[];
  delaysMs: number[];
  reasoning: string;
  suspicionOnMe: number;
  action: AgentAction;
  /**
   * 이번 발화에서 **새로 지어낸 사실** (facts.ts). 모델이 제 출력에 실어 보낸다.
   *
   * ★ 부르는 쪽은 **발화가 실제로 나갔을 때만** 이걸 누적해야 한다. 자리를 놓쳐
   *   버려진 답의 사실까지 쌓으면, 봇이 한 적 없는 말을 했다고 기억한다.
   */
  facts: string[];
}

