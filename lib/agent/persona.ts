/**
 * Persona 인터페이스 — 인물 목록(world-persona.ts)이 쓰는 타입. 소유: B (SPEC §2, §9)
 *
 * 게임 페르소나 4인(태오·민지·준·하늘)과 personaForSeat 은 2026-08-08 에 지웠다 —
 * 2D 게임 방이 흐름에서 빠지면서(대기방에서 시작하면 곧장 월드) 그 인물들이 설
 * 자리가 없어졌다. 같은 날 LLM 덮어쓰기 계층(prefill.ts · chat-reply.ts)도 함께
 * 지웠다. 2D 봇 발화의 SQL 문구 풀은 그대로다 — 되살릴 일이 있으면 git 역사에 있다.
 *
 * 인터페이스에는 "성격"만 둔다. 공통 규칙(정체 부인 · 인젝션 방어 · 출력 형식)은
 * generate.ts의 공통 프롬프트가 얹는다 — 인물을 늘릴 때 규칙을 복붙하지
 * 않기 위해서다.
 *
 * ★ 페르소나끼리 말버릇이 서로 배타여야 한다 (웃음 표기·초성체·물결 등).
 *   같은 모델이 병렬로 여러 명을 연기하면 그냥 둬도 서로 닮는다 — "쓰는 것"만큼
 *   "안 쓰는 것"을 못 박아야 화면에서 갈라진다 (실측된 실패).
 *
 * ★ 웃음을 쓰는 인물에게만 `laugh`를 준다. 그 값은 "웃느냐"가 아니라 **길이를
 *   얼마나 흔드느냐**다 — 8b는 "ㅋㅋ만 쓴다"를 글자 수까지 지켜서 매번 정확히
 *   두 글자로 웃는다 (disguise.ts의 stretchLaugh 상자).
 */

import type { LaughStyle, Speech } from '@/lib/agent/disguise';

export interface Persona {
  id: string;
  /**
   * 이 인물의 이름. `system` 안에도 있지만 **코드가 알아야 해서** 따로 둔다 —
   * 묻지도 않았는데 제 이름을 대는 발화를 걸러내는 데 쓴다 (generate.ts의 isSelfIntro).
   *
   * ★ system의 이름과 반드시 같아야 한다. 어긋나면 그물이 헛돈다 — 검사가 있다.
   */
  name: string;
  /** 봇이 연기하는 성격·말버릇의 축약. 클라이언트에 노출되지 않는다. */
  traits: string[];
  /** 시스템 프롬프트 본문. */
  system: string;
  /**
   * 웃음 표기 성향 — **길이를 흔드는 폭이 인물마다 다르다** (disguise.ts의 상자).
   *
   * 프롬프트에 "ㅋㅋ만 쓴다"라고 적어 둔 인물에게만 준다. 웃음을 안 쓰는 인물은
   * 비워 둔다 — 여기 값을 주면 없던 웃음이 생기는 게 아니라 그냥 무시되지만,
   * 비워 두는 편이 지문 표(파일 머리말)와 어긋나지 않는다.
   */
  laugh?: LaughStyle;
  /**
   * 이 인물이 **안 쓰는 문장부호.** `system`의 "절대 안 쓰는 것" 중 부호만 옮겨 적는다.
   *
   * ┌─ 왜 프롬프트로 안 끝나는가 ───────────────────────────────────────────────┐
   * │ 실측: 느낌표를 금지한 선영이 "안녕하세요!"라고 인사했다. 8b는 인사·감탄     │
   * │ 자리에서 금칙을 자주 놓친다. 부호 하나가 새면 그 인물이 다른 인물과 안      │
   * │ 갈리고(지문 표가 인물을 가르는 방식이다), 인물이 뭉개지면 자리도 묶인다(I1).│
   * │                                                                            │
   * │ ★ 부호만 담는다. 자모(ㅋㅋ·ㅠㅠ)는 지우면 문장이 어색해진다 —              │
   * │   "그러네 ㅎㅎ"에서 웃음만 빼면 남는 건 사람이 안 치는 모양이다.            │
   * └──────────────────────────────────────────────────────────────────────────┘
   */
  avoidPunct?: string[];
  /**
   * 이 인물의 어체. 비우면 반말이다 — 인물 대부분이 반말이라 존댓말 쪽만 적는다.
   *
   * `system`의 "반말이다"/"처음부터 끝까지 존댓말이다"와 **반드시 같아야 한다.**
   * 코드가 알아야 하는 이유는 name과 같다: 프롬프트가 뚫렸을 때 걸러내려면
   * 어느 쪽이 맞는지를 코드도 알아야 한다 (disguise.ts의 enforceSpeech).
   */
  speech?: Speech;
  /**
   * LLM이 실패했을 때 이 인물이 대신 흘릴 말 (generate.ts의 FALLBACK_POOL 대체).
   *
   * ┌─ 왜 인물마다 따로 두는가 ─────────────────────────────────────────────────┐
   * │ 공용 풀은 세 줄뿐이다: "ㅇㅇ" · "아 잠깐만" · "나도 몰루".                   │
   * │ 초성체를 안 쓰기로 한 현수도, 끝까지 존댓말인 선영도 똑같이 "나도 몰루"를    │
   * │ 말한다. 그 순간 인물이 뭉개지고, **인물이 뭉개지면 자리도 같이 묶인다**     │
   * │ (I1 — 지문 표가 인물을 가르는 방식이다).                                    │
   * │                                                                            │
   * │ 게다가 폴백은 드물지 않다. 8b 가 형식을 놓치거나 그물에 걸릴 때마다 나오고,  │
   * │ 그때마다 같은 세 줄이 방을 돈다 — 예전에 하드코딩 문구 풀을 없앤 이유와      │
   * │ 정확히 같은 실패다 (worker/src/bots.ts 끝의 주석).                          │
   * │                                                                            │
   * │ ★ 월드에서는 폴백이 곧 침묵이라(world-agent가 거른다) 여기 값이 안 보인다.  │
   * │   게임 방에서만 실제로 나간다.                                              │
   * └──────────────────────────────────────────────────────────────────────────┘
   *
   * 비우면 공용 풀을 쓴다. 인물의 어체·지문과 어긋나지 않게 적을 것.
   */
  fallbacks?: readonly string[];
}

