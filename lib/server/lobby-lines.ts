/**
 * 대기방에서 누를 수 있는 문구. 소유: A (SPEC §15-3-결정)
 *
 * ┌─ 왜 자유 채팅이 아닌가 ────────────────────────────────────────────────────┐
 * │ 대기방에서 사람들이 미리 짜면 게임이 죽는다. 다만 이 게임은 담합의 두 축을 │
 * │ 이미 구조로 끊어놨다 — 봇은 시작할 때 채워지고(fill_with_bots), 자리·닉네임 │
 * │ 은 시작 순간 다시 섞인다(shuffle_seats). 역할도 그때 배정된다. 그래서      │
 * │ "나 3번이야" 도 "내가 스파이야" 도 대기방에서는 성립하지 않는다.           │
 * │                                                                          │
 * │ 남는 건 하나다 — "우리 다 짧게만 답하자" 같은 **메타 합의**. 자리를 몰라도 │
 * │ 통하고, 사람 전체가 봇 흉내를 내서 스파이를 숨겨준다. 프리셋이 막는 건     │
 * │ 이것이고, 그래서 목록의 기준은 하나다:                                    │
 * │                                                                          │
 * │   **게임 내용에 대해선 한마디도 못 하고, "진행"에 대해서만 말할 수 있다.** │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * ★ 목록을 늘리지 않는다. 문구가 많아질수록 조합이 통신 채널이 된다 —
 *   8개면 3비트라, "ㅋㅋㅋ 두 번 = 나랑 짜자" 같은 약속이 성립한다.
 *   연타·재전송을 막는 규칙(say_lobby_line)이 그래서 같이 있어야 한다.
 *
 * ★ 넣지 않는 것과 이유:
 *     · 숫자·자리 지칭 ("3번", "한 명만 더")  자리 연결. 정원이 방마다 3~8이라
 *                                            수를 박은 문구는 애초에 안 맞는다
 *     · 자유 이모지                           각자 다른 이모지 = 신원 태그
 *     · 역할 언급 ("나 스파이 아님")          로비엔 역할이 없어 거짓말조차 안 되는데,
 *                                            정체 얘기를 여기서부터 시작하게 만든다
 *     · 조각 조합 ("나는" + "봇" + "이다")    문장을 만들 수 있으면 그냥 자유 채팅이다
 *
 * 톤은 bot_line_pool(seed.sql)에 맞춘다 — 전부 반말 구어체다. 여기만 존댓말이면
 * 대기방만 붕 뜬다.
 *
 * ★ "준비 완료"는 이 목록에 없다. 발화가 아니라 상태라서 좌석 카드에 붙고,
 *   /api/lobby/ready 가 따로 받는다. 채팅 로그에 남기면 그 자체가 순서 신호가 된다.
 */

export interface LobbyLine {
  /** 클라이언트가 보내는 값. 문구를 고쳐도 이건 그대로 둔다. */
  id: string;
  text: string;
}

export const LOBBY_LINES: readonly LobbyLine[] = [
  // 진행 — 이게 없으면 대기방이 안 굴러간다
  { id: 'wait', text: '잠깐만' },
  { id: 'start', text: '시작하자' },
  { id: 'hold', text: '조금만 기다려' },

  // 사교 — 담합에 쓸 값이 0인 것들. 이게 있어야 나머지가 신호처럼 안 보인다
  { id: 'hi', text: '안녕' },
  { id: 'lol', text: 'ㅋㅋㅋ' },
  { id: 'nervous', text: '긴장된다' },
  { id: 'lets-go', text: '가보자' },
  { id: 'first-game', text: '첫 판이야' },
] as const;

/** 없는 id면 null. 라우트가 이걸로 화이트리스트를 강제한다 (I9). */
export function lobbyLineText(id: string): string | null {
  return LOBBY_LINES.find((l) => l.id === id)?.text ?? null;
}

